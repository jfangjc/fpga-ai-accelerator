// Shared limits, protocol constants and configuration types of the QNC2
// INT8 engine. Stage S1 executes PING and pointwise RUN_LAYER commands;
// see docs/qnc2_protocol.md (wire format) and docs/engine.md (architecture).
package stt_engine_pkg;
    // RUN_LAYER limits.
    localparam int MAX_CI = 1024;
    localparam int MAX_CO = 1024;
    localparam int MAX_T  = 800;
    localparam int MAX_NT = (MAX_T + 15) / 16;   // 16-frame tiles per channel row

    // Activation banks store one 16-byte word per (channel, 16-frame tile):
    // word address = channel * NT + tile, lane i = frame 16*tile + i.
    localparam int ACT_DEPTH = MAX_CI * MAX_NT;  // 51,200 words per bank
    localparam int ACT_AW    = 16;
    localparam int ACT_LAT   = 4;   // bank (and weight buffer) read latency
    localparam int PARAM_LAT = 2;   // parameter RAM read latency
    localparam int REQUANT_LAT = 8; // stt_requant pipeline depth (no backpressure)

    // Array geometry: 32 output channels x 16 frames, one DSP48E2 per MAC.
    localparam int ARRAY_O = 32;
    localparam int ARRAY_F = 16;
    // Sum of <= 1024 products, |product| <= 128*255:
    // |sum| <= 33,423,360 < 2^25, so 26-bit signed partial sums never wrap.
    localparam int SUM_W = 33; // bias plus all prefixes, including INT32 overflow

    localparam logic [31:0] CMD_MAGIC = 32'h3243_4e51;  // "QNC2"
    localparam logic [31:0] RSP_MAGIC = 32'h3253_4e51;  // "QNS2"
    localparam logic [31:0] REC_MAGIC = 32'h3252_4c51;  // "QLR2"
    localparam logic [31:0] PROTO_VERSION  = 32'd1;
    // [31:16] protocol version, [15:0] engine stage (1 = S1 pointwise).
    localparam logic [31:0] ENGINE_VERSION = 32'h0001_0002;

    localparam logic [31:0] OP_PING      = 32'd0;
    localparam logic [31:0] OP_RUN_LAYER = 32'd1;

    // Response status codes.
    localparam logic [3:0] ST_OK       = 4'd0;
    localparam logic [3:0] ST_MAGIC    = 4'd1;  // magic or version
    localparam logic [3:0] ST_OPCODE   = 4'd2;
    localparam logic [3:0] ST_LENGTH   = 4'd3;  // length, TLAST or TKEEP
    localparam logic [3:0] ST_DESC     = 4'd4;  // limits, record, parameters
    localparam logic [3:0] ST_OVERFLOW = 4'd5;  // INT32 accumulator overflow
    localparam logic [3:0] ST_TIMEOUT  = 4'd6;  // idle-stream watchdog
    localparam logic [3:0] ST_INTERNAL = 4'd7;  // invariant violation (never expected)

    // Decoded RUN_LAYER configuration, valid after the header check.
    typedef struct packed {
        logic        dw;
        logic        add;
        logic [6:0] taps, padding;
        logic [1:0] stride, dilation;
        logic [9:0] tout, vout;
        logic        run;        // RUN_LAYER (0: PING)
        logic        in_signed;  // input INT8 (else UINT8)
        logic        relu;       // output UINT8 [0,255] (else INT8)
        logic [10:0] ci;         // 1..1024
        logic [10:0] co;         // 1..1024
        logic [9:0]  t;          // 1..800 allocated frames
        logic [9:0]  valid;      // 0..t valid frames; later inputs read as zero
        logic [5:0]  nt;         // ceil(t/16)
        logic [4:0]  last_n;     // frames in the final tile, 1..16
        logic [5:0]  n_otile;    // ceil(co/32)
        logic [6:0]  kpt;        // ceil(ci/16) weight K tiles
    } layer_cfg_t;

    // Travels with a frame tile through the array and drain.
    typedef struct packed {
        logic [4:0]        otile;  // output tile: channels 32*otile + row
        logic [ACT_AW-1:0] base;   // output word address of row 0
    } tile_tag_t;
