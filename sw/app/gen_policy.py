"""Generate the application contract without importing model dependencies."""
import json
import runpy
from pathlib import Path

root = Path(__file__).resolve().parents[2]
p = runpy.run_path(str(root / 'model/stream_policy.py'))
p = {k: v for k, v in p.items() if k.isupper()}
out = Path(__file__).parent
(out / 'policy.json').write_text(json.dumps(p, indent=2) + '\n')
with (out / 'policy.h').open('w') as f:
    f.write('/* Generated by gen_policy.py; do not edit. */\n#pragma once\n')
    for k, v in p.items():
        if isinstance(v, (int, float, str)):
            f.write(f'#define POLICY_{k} {json.dumps(v)}\n')
